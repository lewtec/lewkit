package generate

import (
	"os"
	"path/filepath"
)

// Notice is the banner line of a generated Go file, without comment marks.
func Notice(command string) string {
	return "Code generated by lewkit generate " + command + ". DO NOT EDIT."
}

// WriteFile writes buf to path by renaming path.tmp into place.
// The parent directory is created at mode 0o755. The file mode is 0o644.
func WriteFile(path string, buf []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, buf, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
