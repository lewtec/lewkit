package generate

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestNotice(t *testing.T) {
	t.Parallel()
	require.Equal(t, "Code generated by lewkit generate header. DO NOT EDIT.", Notice("header"))
	require.Equal(t, "Code generated by lewkit generate clib. DO NOT EDIT.", Notice("clib"))
	require.Equal(t, "Code generated by lewkit generate shader. DO NOT EDIT.", Notice("shader"))
	require.Equal(t, "Code generated by lewkit generate prelude. DO NOT EDIT.", Notice("prelude"))
	require.Equal(t, "Code generated by lewkit generate db. DO NOT EDIT.", Notice("db"))
}

func TestWriteFile(t *testing.T) {
	t.Parallel()
	path := filepath.Join(t.TempDir(), "out", "bind.go")
	require.NoError(t, WriteFile(path, []byte("package bind\n")))
	got, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, "package bind\n", string(got))
	_, err = os.Stat(path + ".tmp")
	require.ErrorIs(t, err, os.ErrNotExist)
}
