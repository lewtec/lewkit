func generatedFor(t *testing.T, dir, goos, goarch string) string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	require.NoError(t, err)
	var hit string
	for _, entry := range entries {
		if !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		buf, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		require.NoError(t, err)
		line, _, _ := strings.Cut(string(buf), "\n")
		expr, err := constraint.Parse(line)
		require.NoError(t, err, entry.Name())
		if expr.Eval(func(tag string) bool { return tag == goos || tag == goarch }) {
			require.Empty(t, hit, "two files match %s/%s", goos, goarch)
			hit = string(buf)
		}
	}
	require.NotEmpty(t, hit, "%s/%s", goos, goarch)
	return hit
}

