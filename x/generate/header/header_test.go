func TestPlatformLayouts(t *testing.T) {
	apple, err := For("darwin", "arm64")
	require.NoError(t, err)
	assert.Equal(t, 8, apple.LongDouble)
	assert.Equal(t, "darwinarm64", apple.ID)
	linuxArm, err := For("linux", "arm64")
	require.NoError(t, err)
	assert.Equal(t, 16, linuxArm.LongDouble)
	win, err := For("windows", "amd64")
	require.NoError(t, err)
	assert.Equal(t, 4, win.Long)
	if runtime.GOOS == "linux" && runtime.GOARCH == "amd64" {
		assert.Equal(t, "linux && amd64", Host().Constraint())
	}

	const src = "struct LL { char a; long long b; };\nstruct LD { char a; long double b; };\n"
	cases := []struct {
		goos, goarch   string
		llOff, ldOff   int
		ldSize, ldAlgn int
	}{
		{"linux", "amd64", 8, 16, 16, 16},
		{"linux", "arm64", 8, 16, 16, 16},
		{"darwin", "arm64", 8, 8, 8, 8},
		{"linux", "386", 4, 4, 12, 4},
		{"windows", "386", 8, 8, 8, 8},
		{"windows", "amd64", 8, 8, 8, 8},
		{"linux", "arm", 8, 8, 8, 8},
	}
	for _, tc := range cases {
		target, err := For(tc.goos, tc.goarch)
		require.NoError(t, err)
		unit := parseHeader(t, src, target)
		ll := findType(t, unit, "LL")
		ld := findType(t, unit, "LD")
		assert.Equal(t, tc.llOff, fieldOf(t, ll, "b").Offset, "%s/%s long long", tc.goos, tc.goarch)
		assert.Equal(t, tc.ldOff, fieldOf(t, ld, "b").Offset, "%s/%s long double", tc.goos, tc.goarch)
		assert.Equal(t, tc.ldSize, fieldOf(t, ld, "b").Type.Size, "%s/%s long double size", tc.goos, tc.goarch)
		assert.Equal(t, tc.ldAlgn, fieldOf(t, ld, "b").Type.Align, "%s/%s long double align", tc.goos, tc.goarch)
	}
}

func TestPlatformMacros(t *testing.T) {
	const src = `
#if defined(_WIN64)
typedef int win64_flag;
#endif
#if defined(_WIN32)
typedef int win32_flag;
#endif
#if defined(__ANDROID__)
typedef int android_flag;
#endif
#if defined(__linux__)
typedef int linux_flag;
#endif
#if defined(__APPLE__)
typedef int apple_flag;
#endif
`
	has := func(goos, goarch, name string) bool {
		t.Helper()
		target, err := For(goos, goarch)
		require.NoError(t, err)
		_, ok := typedefSpell(parseHeader(t, src, target), name)
		return ok
	}
	assert.True(t, has("windows", "amd64", "win64_flag"))
	assert.True(t, has("windows", "amd64", "win32_flag"))
	assert.False(t, has("windows", "386", "win64_flag"))
	assert.True(t, has("windows", "386", "win32_flag"))
	assert.True(t, has("android", "arm64", "android_flag"))
	assert.True(t, has("android", "arm64", "linux_flag"))
	assert.False(t, has("linux", "amd64", "android_flag"))
	assert.True(t, has("linux", "amd64", "linux_flag"))
	assert.True(t, has("darwin", "arm64", "apple_flag"))
	assert.False(t, has("linux", "arm64", "apple_flag"))
}

func TestAllABIs(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, Run(t.Context(), Config{
		File:    filepath.Join("testdata", "sample.h"),
		Out:     filepath.Join(dir, "sample.go"),
		Package: "bind",
		Libs:    []string{"libsample.so"},
	}))
	entries, err := os.ReadDir(dir)
	require.NoError(t, err)
	type tagged struct {
		name string
		expr constraint.Expr
	}
	var files []tagged
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		buf, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		require.NoError(t, err)
		line, _, _ := strings.Cut(string(buf), "\n")
		require.True(t, strings.HasPrefix(line, "//go:build "), entry.Name())
		expr, err := constraint.Parse(line)
		require.NoError(t, err, entry.Name())
		assert.Contains(t, string(buf), "Code generated by lewkit generate header. DO NOT EDIT.")
		files = append(files, tagged{name: entry.Name(), expr: expr})
	}
	require.NotEmpty(t, files)
	targets := allTargets()
	require.Len(t, targets, len(platformPairs()))
	for _, target := range targets {
		match := 0
		for _, file := range files {
			ok := file.expr.Eval(func(tag string) bool {
				return tag == target.GOOS || tag == target.GOARCH
			})
			if ok {
				match++
			}
		}
		require.Equal(t, 1, match, "%s/%s", target.GOOS, target.GOARCH)
	}

	require.NoError(t, os.WriteFile(filepath.Join(dir, "compile_test.go"), []byte(compileStub), 0o644))
	mod := "module example.com/bind\n\ngo 1.27.0\n\nrequire github.com/lewtec/lewkit v0.0.0\n\nreplace github.com/lewtec/lewkit => " +
		moduleRoot(t) + "\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(mod), 0o644))
	// android needs cgo for purego's dlfcn, so this check stays on the
	// GOOS/GOARCH pairs that build with CGO_ENABLED=0.
	for _, pair := range [][2]string{
		{"linux", "amd64"},
		{"linux", "arm64"},
		{"darwin", "arm64"},
		{"windows", "amd64"},
		{"linux", "386"},
		{"linux", "arm"},
		{"windows", "386"},
	} {
		cmd := exec.Command("go", "test", "-c", "-mod=mod", "-o", filepath.Join(dir, "bind.test"), ".")
		cmd.Dir = dir
		cmd.Env = append(goEnv(), "GOOS="+pair[0], "GOARCH="+pair[1], "CGO_ENABLED=0")
		out, err := cmd.CombinedOutput()
		require.NoError(t, err, "%s/%s: %s", pair[0], pair[1], out)
	}
}

