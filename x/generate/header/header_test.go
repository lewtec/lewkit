func TestParseSample(t *testing.T) {
	if runtime.GOOS != "linux" || runtime.GOARCH != "amd64" {
		t.Skip("oracle is the host C ABI")
	}
	unit := parseSample(t)
	point := findType(t, unit, "Point")
	require.Equal(t, 24, point.Size)
	require.Equal(t, 8, point.Align)
	require.Equal(t, 0, fieldOf(t, point, "tag").Offset)
	require.Equal(t, 4, fieldOf(t, point, "x").Offset)
	require.Equal(t, 8, fieldOf(t, point, "y").Offset)
	require.Equal(t, 16, fieldOf(t, point, "z").Offset)

	oracle := gccOracle(t)
	for _, typ := range unit.Types {
		if typ.Kind != kindStruct && typ.Kind != kindUnion && typ.Kind != kindEnum {
			continue
		}
		if typ.Tag == "" || typ.Incomplete {
			continue
		}
		got, ok := oracle.types[typ.Tag]
		if !ok {
			continue
		}
		assert.Equal(t, got.size, typ.Size, "sizeof %s", typ.Tag)
		assert.Equal(t, got.align, typ.Align, "alignof %s", typ.Tag)
		for _, field := range typ.Fields {
			if field.Name == "" || field.IsBit {
				continue
			}
			off, ok := oracle.fields[typ.Tag+"."+field.Name]
			if !ok {
				continue
			}
			assert.Equal(t, off, field.Offset, "offsetof %s.%s", typ.Tag, field.Name)
		}
	}

	require.Equal(t, int64(42), constOf(t, unit, "ANSWER"))
	require.Equal(t, int64(0x10), constOf(t, unit, "FLAG"))
	require.Equal(t, int64(4), constOf(t, unit, "SUM"))
	_, no := typedefSpell(unit, "no_flag")
	assert.False(t, no)
	yes, ok := typedefSpell(unit, "yes_flag")
	assert.True(t, ok)
	assert.Equal(t, kindAlias, yes.Kind)

	var names []string
	for _, fn := range unit.Funcs {
		names = append(names, fn.Name)
	}
	assert.Equal(t, []string{"point_sum", "slot_ptr"}, names)
	assert.Contains(t, unit.Skipped, "variadic")

	arr := findType(t, unit, "Arr")
	require.Equal(t, kindArray, fieldOf(t, arr, "c").Type.Kind)
	require.Equal(t, kindPtr, fieldOf(t, arr, "c").Type.Elem.Kind)
	require.Equal(t, kindPtr, fieldOf(t, arr, "d").Type.Kind)
	require.Equal(t, kindArray, fieldOf(t, arr, "d").Type.Elem.Kind)
	require.Equal(t, kindArray, fieldOf(t, arr, "f").Type.Kind)
	require.Equal(t, kindPtr, fieldOf(t, arr, "f").Type.Elem.Kind)
	require.Equal(t, kindFunc, fieldOf(t, arr, "f").Type.Elem.Elem.Kind)

	color := findType(t, unit, "Color")
	require.Equal(t, []int64{1, 2, 4}, []int64{color.Enums[0].Value, color.Enums[1].Value, color.Enums[2].Value})
}

func TestWriteSample(t *testing.T) {
	if runtime.GOOS != "linux" || runtime.GOARCH != "amd64" {
		t.Skip("generated file targets the host ABI")
	}
	unit := parseSample(t)
	buf, err := Write(unit, "bind", []string{"libsample.so"})
	require.NoError(t, err)
	text := string(buf)
	require.True(t, strings.HasPrefix(text, "//go:build "), text[:80])
	assert.Contains(t, text, "Code generated by lewkit generate header. DO NOT EDIT.")
	assert.Contains(t, text, "structs.HostLayout")
	assert.Contains(t, text, "func Bind(")
	assert.Contains(t, text, "func Open(")
	assert.Contains(t, text, "Skipped variadic: variadic")
	assert.NotContains(t, text, "hidden")
	assert.NotContains(t, text, "func Variadic")

	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "sample_purego.go"), buf, 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "layout_test.go"), []byte(bindLayoutTest), 0o644))
	mod := "module example.com/bind\n\ngo 1.27.0\n\nrequire github.com/lewtec/lewkit v0.0.0\n\nreplace github.com/lewtec/lewkit => " +
		moduleRoot(t) + "\n"
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte(mod), 0o644))
	cmd := exec.Command("go", "test", "-mod=mod", ".")
	cmd.Dir = dir
	cmd.Env = goEnv()
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s", out)
}

