func findType(t *testing.T, unit *Unit, name string) *Type {
	t.Helper()
	for _, typ := range unit.Types {
		if typ.Tag == name || typ.Spell == name || typ.prefer == name {
			return typ
		}
	}
	t.Fatalf("missing type %s", name)
	return nil
}

func fieldOf(t *testing.T, typ *Type, name string) *Field {
	t.Helper()
	for _, field := range typ.Fields {
		if field.Name == name {
			return field
		}
	}
	t.Fatalf("missing field %s.%s", typ.Tag, name)
	return nil
}

func constOf(t *testing.T, unit *Unit, name string) int64 {
	t.Helper()
	for _, c := range unit.Consts {
		if c.Name == name {
			return c.Value
		}
	}
	t.Fatalf("missing const %s", name)
	return 0
}

func typedefSpell(unit *Unit, name string) (*Type, bool) {
	for _, typ := range unit.Types {
		if typ.Spell == name || typ.prefer == name {
			return typ, true
		}
	}
	return nil, false
}

type cLayout struct {
	types  map[string]struct{ size, align int }
	fields map[string]int
}

func gccOracle(t *testing.T) cLayout {
	t.Helper()
	dir := t.TempDir()
	src := filepath.Join(dir, "lay.c")
	header, err := filepath.Abs(filepath.Join("testdata", "sample.h"))
	require.NoError(t, err)
	program := `#include <stddef.h>
#include <stdio.h>
#include "sample.h"
#define S(name, t) printf("S %s %zu %zu\n", name, sizeof(t), _Alignof(t))
#define F(name, t, f) printf("F %s %s %zu\n", name, #f, offsetof(t, f))
int main(void) {
	S("Point", Point); S("Slot", Slot); S("Packed", struct Packed); S("Outer", struct Outer);
	S("Bit", struct Bit); S("Bit2", struct Bit2); S("Aligned", struct Aligned); S("Hold", struct Hold);
	S("Arr", struct Arr); S("R", struct R); S("Extra", struct Extra); S("Color", enum Color);
	F("Point", Point, tag); F("Point", Point, x); F("Point", Point, y); F("Point", Point, z);
	F("Packed", struct Packed, a); F("Packed", struct Packed, b);
	F("Outer", struct Outer, inner); F("Outer", struct Outer, c); F("Outer", struct Outer, hook);
	F("Outer", struct Outer, name); F("Outer", struct Outer, flex);
	F("Bit", struct Bit, c); F("Bit2", struct Bit2, c);
	F("Aligned", struct Aligned, a); F("Aligned", struct Aligned, b);
	F("Hold", struct Hold, a); F("Hold", struct Hold, z); F("Hold", struct Hold, s);
	F("Arr", struct Arr, c); F("Arr", struct Arr, d); F("Arr", struct Arr, f);
	F("R", struct R, b);
	F("Extra", struct Extra, n);
	return 0;
}
`
	require.NoError(t, os.WriteFile(src, []byte(program), 0o644))
	bin := filepath.Join(dir, "lay")
	cmd := exec.Command("gcc", "-std=gnu11", "-I", filepath.Dir(header), "-o", bin, src)
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "%s", out)
	got, err := exec.Command(bin).CombinedOutput()
	require.NoError(t, err, "%s", got)
	lay := cLayout{
		types:  map[string]struct{ size, align int }{},
		fields: map[string]int{},
	}
	for _, line := range strings.Split(string(got), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 {
			continue
		}
		switch fields[0] {
		case "S":
			require.Len(t, fields, 4, line)
			size, err := strconv.Atoi(fields[2])
			require.NoError(t, err)
			align, err := strconv.Atoi(fields[3])
			require.NoError(t, err)
			name := fields[1]
			name = strings.TrimPrefix(name, "enum")
			lay.types[name] = struct{ size, align int }{size, align}
		case "F":
			require.Len(t, fields, 4, line)
			off, err := strconv.Atoi(fields[3])
			require.NoError(t, err)
			lay.fields[fields[1]+"."+fields[2]] = off
		default:
			t.Fatalf("gcc line %q", line)
		}
	}
	return lay
}

