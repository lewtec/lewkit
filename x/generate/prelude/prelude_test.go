func TestRunEmptyDir(t *testing.T) {
	err := Run(t.Context(), "", "")
	assert.ErrorIs(t, err, errDirRequired)
}

func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	fsys, err := path.Open(root)
	require.NoError(t, err)
	test.CloseOnCleanup(t, fsys)
	for rel, body := range files {
		name := path.New(rel)
		if parent := name.Parent(); parent.String() != "." {
			require.NoError(t, parent.MkdirAll(fsys, 0o755))
		}
		require.NoError(t, name.WriteFile(fsys, []byte(body), 0o644))
	}
}

func readPath(t *testing.T, fsys *path.Root, name path.Path) string {
	t.Helper()
	body, err := name.ReadFile(fsys)
	require.NoError(t, err)
	return string(body)
}
