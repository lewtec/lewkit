package clib

import (
	"context"
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/lewtec/lewkit/x/generate/header"
)

// Config is the lewkit generate clib invocation.
type Config struct {
	File    string
	Out     string
	Package string
	Include []string
	Define  []string
	// Bind names the struct whose fields are the C functions. Empty means API.
	Bind string
}

// Run reads File as a linux/amd64 header and writes the Go stubs, the
// SysV trampolines, and _cgo_clib_export.go. Out defaults to
// <stem>_clib.go beside the header. One header per package: a later run
// replaces the export file.
func Run(ctx context.Context, cfg Config) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if cfg.File == "" {
		return ErrHeader
	}
	target, err := header.ParseABI("linux/amd64")
	if err != nil {
		return err
	}
	unit, err := header.Parse(ctx, cfg.File, header.Options{
		Include: cfg.Include,
		Define:  cfg.Define,
		Target:  target,
	})
	if err != nil {
		return err
	}
	dir, goFile, asmFile, exportFile := outputPaths(cfg.File, cfg.Out)
	pkg := cfg.Package
	if pkg == "" {
		pkg = inferPackage(dir)
	}
	if !token.IsIdentifier(pkg) || token.IsKeyword(pkg) {
		return fmt.Errorf("package name: %s", pkg)
	}
	bind := cfg.Bind
	if bind == "" {
		bind = "API"
	}
	if !token.IsIdentifier(bind) || token.IsKeyword(bind) {
		return fmt.Errorf("%w: %s", ErrSymbol, bind)
	}
	funcs, err := classify(unit.Funcs)
	if err != nil {
		return err
	}
	if len(funcs) == 0 {
		return ErrEmpty
	}
	goSrc, err := emitGo(pkg, bind, unit.Skipped, funcs)
	if err != nil {
		return err
	}
	if err := writeAtomic(goFile, goSrc); err != nil {
		return err
	}
	if err := writeAtomic(asmFile, emitAsm(funcs)); err != nil {
		return err
	}
	return writeAtomic(exportFile, emitExport(pkg, funcs))
}

func outputPaths(file, out string) (dir, goFile, asmFile, exportFile string) {
	dir = filepath.Dir(file)
	stem := strings.TrimSuffix(filepath.Base(file), filepath.Ext(file))
	if strings.HasSuffix(out, ".go") {
		goFile = out
		dir = filepath.Dir(out)
	} else {
		if out != "" {
			dir = out
		}
		goFile = filepath.Join(dir, stem+"_clib.go")
	}
	base := strings.TrimSuffix(filepath.Base(goFile), ".go")
	asmFile = filepath.Join(dir, base+"_linux_amd64.s")
	exportFile = filepath.Join(dir, exportFileName)
	return dir, goFile, asmFile, exportFile
}

const exportFileName = "_cgo_clib_export.go"

const generatedBy = "Code generated by lewkit generate clib. DO NOT EDIT."

func writeAtomic(path string, buf []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, buf, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func inferPackage(dir string) string {
	entries, err := os.ReadDir(dir)
	if err == nil {
		for _, entry := range entries {
			name := entry.Name()
			if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
				continue
			}
			if strings.HasPrefix(name, "_") {
				continue
			}
			path := filepath.Join(dir, name)
			if generatedSource(path) {
				continue
			}
			pkg, err := packageClause(path)
			if err == nil && pkg != "" {
				return pkg
			}
		}
	}
	base := filepath.Base(dir)
	if base != "" && base != "." && token.IsIdentifier(base) && !token.IsKeyword(base) {
		r, _ := utf8.DecodeRuneInString(base)
		if unicode.IsLetter(r) {
			return base
		}
	}
	return "main"
}

func generatedSource(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	buf := make([]byte, 512)
	n, _ := f.Read(buf)
	return strings.Contains(string(buf[:n]), generatedBy)
}

func packageClause(file string) (string, error) {
	parsed, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.PackageClauseOnly)
	if err != nil {
		return "", err
	}
	if parsed.Name == nil {
		return "", fmt.Errorf("package name")
	}
	return parsed.Name.Name, nil
}
