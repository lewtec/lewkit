package parse

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestFormat(t *testing.T) {
	t.Parallel()
	got := format("c", "cTable", []byte("LK01\x00"))
	assert.Equal(t, "// Code generated by lewkit generate parse. DO NOT EDIT.\n\npackage c\n\nvar cTable = []byte(\"LK01\\x00\")\n", string(got))
}

func TestRunWritesTable(t *testing.T) {
	dir := writeModule(t, `package sample

func ParseTable() ([]byte, error) {
	return []byte("LK01hi"), nil
}
`)
	t.Setenv("GOFILE", filepath.Join(dir, "grammar.go"))
	require.NoError(t, Run(t.Context()))
	got, err := os.ReadFile(filepath.Join(dir, tableFile))
	require.NoError(t, err)
	assert.Equal(t, string(format("sample", "sampleTable", []byte("LK01hi"))), string(got))

	require.NoError(t, Run(t.Context()))
	again, err := os.ReadFile(filepath.Join(dir, tableFile))
	require.NoError(t, err)
	assert.Equal(t, got, again)
	_, err = os.Stat(filepath.Join(dir, emitFile))
	assert.ErrorIs(t, err, os.ErrNotExist)
}

func TestRunParseTableError(t *testing.T) {
	dir := writeModule(t, `package sample

import "errors"

func ParseTable() ([]byte, error) {
	return nil, errors.New("boom")
}
`)
	t.Setenv("GOFILE", filepath.Join(dir, "grammar.go"))
	err := Run(t.Context())
	assert.ErrorIs(t, err, ErrTable)
	assert.ErrorContains(t, err, "boom")
	_, statErr := os.Stat(filepath.Join(dir, tableFile))
	assert.ErrorIs(t, statErr, os.ErrNotExist)
	_, statErr = os.Stat(filepath.Join(dir, emitFile))
	assert.ErrorIs(t, statErr, os.ErrNotExist)
}

func TestRunRejectsPlainBytes(t *testing.T) {
	dir := writeModule(t, `package sample

func ParseTable() ([]byte, error) {
	return []byte("nope"), nil
}
`)
	t.Setenv("GOFILE", filepath.Join(dir, "grammar.go"))
	err := Run(t.Context())
	assert.ErrorIs(t, err, ErrTable)
	_, statErr := os.Stat(filepath.Join(dir, emitFile))
	assert.ErrorIs(t, statErr, os.ErrNotExist)
}

func TestRunNoPackage(t *testing.T) {
	t.Setenv("GOFILE", filepath.Join(t.TempDir(), "grammar.go"))
	err := Run(t.Context())
	assert.ErrorIs(t, err, ErrNoPackage)
}

func TestRunCancel(t *testing.T) {
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	err := Run(ctx)
	assert.ErrorIs(t, err, context.Canceled)
}

func writeModule(t *testing.T, parseSrc string) string {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/sample\n\ngo 1.27.0\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "parse.go"), []byte(parseSrc), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "grammar.go"), []byte("package sample\n\n//go:generate go run github.com/lewtec/lewkit/cmd/lewkit generate parse\n"), 0o644))
	return dir
}
