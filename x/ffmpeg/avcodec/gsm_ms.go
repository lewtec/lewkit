	put(6)
	sr = gsmMix(sr, 4, larc[5], 12)
	sr = gsmMix(sr, 3, larc[6], 13)
	put(7)
	sr = gsmMix(sr, 3, larc[7], 13)
	sr = gsmMix(sr, 7, nc[0], 9)
	put(5)
	sr = gsmMix(sr, 2, bc[0], 14)
	sr = gsmMix(sr, 2, mc[0], 14)
	sr = gsmMix(sr, 6, xmaxc[0], 10)
	put(3)
	sr = gsmMix(sr, 3, xmc[0], 13)
	put(8)
	sr = gsmMix(sr, 3, xmc[1], 13)
	sr = gsmMix(sr, 3, xmc[2], 13)
