//go:build ignore

// genversion writes version_gen.go from the lucide modot pin.
package main

import (
	"fmt"
	"go/format"
	"os"

	"github.com/lewtec/lewkit/x/generate"
	"github.com/lewtec/lewkit/x/http/asset/lucide/internal/pin"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "genversion: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := pin.ModuleRoot("")
	if err != nil {
		return err
	}
	version, err := pin.Version(root)
	if err != nil {
		return err
	}
	body := fmt.Sprintf(`// Code generated by go run genversion.go. DO NOT EDIT.

package lucide

// Version is the Lucide release these bodies were taken from.
// The modot input github:lucide-icons/lucide owns the tag.
const Version = %q
`, version)
	formatted, err := format.Source([]byte(body))
	if err != nil {
		return err
	}
	return generate.WriteFile("version_gen.go", formatted)
}
